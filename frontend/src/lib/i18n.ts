import { useSyncExternalStore } from 'react'

export type Lang = 'en' | 'ar'

const KEY = 'thebes-audit-lang'
let current: Lang = (() => {
  try { return (localStorage.getItem(KEY) as Lang) || 'en' } catch { return 'en' }
})()
const listeners = new Set<() => void>()

function apply(l: Lang) {
  document.documentElement.lang = l
  document.documentElement.dir = l === 'ar' ? 'rtl' : 'ltr'
}
if (typeof document !== 'undefined') apply(current)

export function setLang(l: Lang) {
  current = l
  try { localStorage.setItem(KEY, l) } catch { /* private mode: the choice lasts the session */ }
  apply(l)
  listeners.forEach((f) => f())
}

export function useLang(): Lang {
  return useSyncExternalStore((f) => { listeners.add(f); return () => listeners.delete(f) }, () => current)
}

