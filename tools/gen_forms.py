#!/usr/bin/env python3
"""The forms of the audit cycle, and their generator.

Writes forms/<id>.json (the readable catalogue), motoko/src/FormsSeed.mo (forms 1 to 14,
regenerated byte for byte: the module an existing instance was signed under never changes),
motoko/src/FormsSeedExt.mo (forms 15 onwards) and forms/GRAPH.json with motoko/src/FormGraph.mo
(the dependency graph between forms, derived from the definitions). Each form is authored
from the requirements of the standard it serves, in our own words; no vendor form text,
numbering or template prose is reproduced.

ARABIC. Arabic labels and letter text are a first draft for professional review
(`ar_status: draft_pending_review`). Where a term has a sourced Arabic equivalent
in thebes-audit-standards seed/terms.json (the IAASB handbook Arabic translation,
or the existing product), that equivalent is used; the rest is drafted and must be
reviewed by a qualified auditor before client use, per the programme's
terminology policy.

AUTOFILL expressions a field may carry (resolved by src/Forms.mo at view time and
frozen into the values when the form is signed as prepared):
  engagement.<client|period_start|period_end|currency|framework|audit_standard>
  engagement.members             the team (table rows: principal, role)
  tb.benchmark.<revenue|total_assets|profit_before_tax|total_equity|total_expenses|gross_profit|net_assets>
  tb.benchmark.{field}            the benchmark named by another field of this form
  tb.leadsheet.<LS-ID>[.prior]    a leadsheet's net from the latest accepted trial balance
  paper.<kind>.<dot.path>         the latest working paper of that computation
  records.<RK-KIND>               the engagement's records of that kind (table rows)
  records.<RK-KIND>.open          how many of them are not in a closing state
  records.<RK-KIND>.for.<P-ID>    how many of them cite a procedure
  seed.presumed_risks             the model's presumed and significant risks (table rows)
  disclosures.open                open items of the disclosure checklist
  programme.open                  applicable procedures without a reviewed conclusion
  group.components                the group ladder (table rows)
  form.<F-ID>.<field>             another form's effective value (frozen if signed)

COVERAGE. Every procedure of the model is served by a form that declares it or by the
computation the model assigns it; the generator refuses a catalogue that leaves one
unserved.

Attribution: Thebes Core Team. Licence: Apache 2.0.
"""
