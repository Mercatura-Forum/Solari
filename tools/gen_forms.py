def mo(s):
    out = []
    for ch in s:
        o = ord(ch)
        if ch == '\\':
            out.append('\\\\')
        elif ch == '"':
            out.append('\\"')
        elif o < 32 or o == 127:
            out.append('\\u{%x}' % o)
        else:
            out.append(ch)
    return '"' + ''.join(out) + '"'


AUTOFILL_ROOTS = ('engagement', 'tb', 'paper', 'records', 'seed', 'disclosures', 'programme', 'group', 'adjustments', 'controls', 'form')


def check(forms, procedures, standards):
    """Structural checks and coverage, so a malformed or incomplete catalogue never reaches the canister."""
    import re
    types = {'text', 'textarea', 'date', 'money', 'percent', 'integer', 'select', 'yesno', 'table'}
    known_p = {p['id']: p for p in procedures}
    known_s = {x['id'] for x in standards}
    ids = set()
    numbers = set()
    problems = []
    fields_of = {}
    for f in forms:
        if f['id'] in ids:
            problems.append(f'duplicate form id {f["id"]}')
        ids.add(f['id'])
        if f['number'] in numbers:
            problems.append(f'{f["id"]}: duplicate number {f["number"]}')
        numbers.add(f['number'])
        if not re.fullmatch(r'F\d\d-[A-Z0-9-]+', f['id']) or int(f['id'][1:3]) != f['number']:
            problems.append(f'{f["id"]}: id and number disagree')
        if f['phase'] not in ('planning', 'fieldwork', 'completion') or f['kind'] not in ('worksheet', 'letter', 'checklist'):
            problems.append(f'{f["id"]}: unknown phase or kind')
        for pid in f['procedures']:
            if pid not in known_p:
                problems.append(f'{f["id"]}: unknown procedure {pid}')
        for sid in f['standards']:
            if sid not in known_s:
                problems.append(f'{f["id"]}: unknown standard {sid}')
        for lang in ('en', 'ar'):
            if not f['title'].get(lang) or not f['purpose'].get(lang):
                problems.append(f'{f["id"]}: missing {lang} title or purpose')
        for stage in ('prepare', 'review', 'approve'):
            if not f['signoff'].get(stage):
                problems.append(f'{f["id"]}: sign-off stage {stage} names no role')
        seen = set()
        for s_ in f['sections']:
            for lang in ('en', 'ar'):
                if not s_['title'].get(lang):
                    problems.append(f'{f["id"]}.{s_["id"]}: missing {lang} section title')
            for fd in s_['fields']:
                if fd['id'] in seen:
                    problems.append(f'{f["id"]}: duplicate field {fd["id"]}')
                seen.add(fd['id'])
                if fd['type'] not in types:
                    problems.append(f'{f["id"]}.{fd["id"]}: unknown type {fd["type"]}')
                if fd['type'] == 'select' and not fd.get('options'):
                    problems.append(f'{f["id"]}.{fd["id"]}: select without options')
                if fd['type'] == 'table' and not fd.get('columns'):
                    problems.append(f'{f["id"]}.{fd["id"]}: table without columns')
                for lang in ('en', 'ar'):
                    if not fd['label'].get(lang):
                        problems.append(f'{f["id"]}.{fd["id"]}: missing {lang} label')
                    for o in fd.get('options', []):
                        if not o['label'].get(lang):
                            problems.append(f'{f["id"]}.{fd["id"]}: option {o["value"]} missing {lang} label')
                    for c in fd.get('columns', []):
                        if not c['label'].get(lang):
                            problems.append(f'{f["id"]}.{fd["id"]}: column {c["id"]} missing {lang} label')
                af = fd.get('autofill')
                if af and af.split('.')[0] not in AUTOFILL_ROOTS:
                    problems.append(f'{f["id"]}.{fd["id"]}: autofill root unknown in {af}')
        fields_of[f['id']] = seen
        if f['kind'] == 'letter':
            for lang in ('en', 'ar'):
                for para in f['letter'][lang]:
                    for ref in re.findall(r'\{\{(field|table):([a-z_]+)\}\}', para):
                        if ref[1] not in seen:
                            problems.append(f'{f["id"]}: letter references unknown field {ref[1]}')
            if len(f['letter']['en']) != len(f['letter']['ar']):
                problems.append(f'{f["id"]}: English and Arabic letters differ in paragraph count')
    # form.<id>.<field> names an existing form and field
    for f in forms:
        for s_ in f['sections']:
            for fd in s_['fields']:
                af = fd.get('autofill', '')
                if af.startswith('form.'):
                    parts = af.split('.')
                    if len(parts) != 3 or parts[1] not in fields_of or parts[2] not in fields_of[parts[1]]:
                        problems.append(f'{f["id"]}.{fd["id"]}: {af} names no known form field')
    # coverage: every procedure served by a form or by its computation
    served = {pid for f in forms for pid in f['procedures']}
    unserved = [p['id'] for p in procedures if p['id'] not in served and not p.get('computation_id')]
    if unserved:
        problems.append(f'{len(unserved)} procedures served by no form and no computation: {", ".join(unserved)}')
    return problems


def write_module(path, forms, doc):
    lines = ['// GENERATED by tools/gen_forms.py from the form catalogue. Do not edit.',
             '// Attribution: Thebes Core Team. Licence: Apache 2.0.', '', 'module {',
             f'  /// {doc}',
             '  public let FORMS : [(Text, Text)] = [']
    for f in forms:
        lines.append(f'    ("{f["id"]}", {mo(json.dumps(f, ensure_ascii=False, separators=(",", ":")))}),')
    lines += ['  ];', '',
              '  public func get(id : Text) : ?Text {',
              '    for ((k, v) in FORMS.vals()) { if (k == id) return ?v };',
              '    null',
              '  };', '};']
    text = '\n'.join(lines) + '\n'
    if os.path.exists(path) and path in (OUT, OUT_EXT):
        old = open(path, encoding='utf-8').read()
        if old != text:
            raise SystemExit(f'{os.path.relpath(path)} would change: forms are signed under this module and it must be regenerated byte for byte; a revised form is a new version in a new module')
        return
    with open(path, 'w', encoding='utf-8') as fh:
        fh.write(text)


def frozen_path(fid, version):
    return os.path.join(FROZEN_DIR, f'{fid}@{version}.json')


def freeze_earlier_versions(catalogue):
    """Every version below a form's current one is kept byte for byte under forms/frozen/, so
    the module an instance was signed under is regenerated unchanged. A version that was
    current at the last run is frozen from forms/<id>.json; an earlier one must already be
    frozen."""
    os.makedirs(FROZEN_DIR, exist_ok=True)
    frozen = 0
    for f in catalogue:
        if f['version'] > MAX_VERSION:
            raise SystemExit(f'{f["id"]} is version {f["version"]}: add a module for that version to the generator and to ProductForms.mo first')
        for pv in range(1, f['version']):
            path = frozen_path(f['id'], pv)
            if os.path.exists(path):
                continue
            current = os.path.join(FORMS_DIR, f['id'] + '.json')
            if os.path.exists(current):
                prev = json.load(open(current, encoding='utf-8'))
                if prev.get('version', 1) == pv:
                    with open(path, 'w', encoding='utf-8') as fh:
                        json.dump(prev, fh, ensure_ascii=False, indent=1)
                    frozen += 1
                    continue
            raise SystemExit(f'no frozen definition for {f["id"]} version {pv}: it must be kept under forms/frozen/ before version {f["version"]} can be generated')
    return frozen


def at_version(f, version):
    """The form's definition at a version: the current one, or the frozen artefact."""
    if f['version'] == version:
        return f
    return json.load(open(frozen_path(f['id'], version), encoding='utf-8'))


