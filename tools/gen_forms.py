def main():
    procedures = seed('procedures')
    leadsheets = seed('leadsheets')
    standards = seed('standards')
    catalogue = FORMS + forms_families_a.FORMS + forms_families_b.FORMS + [forms_families_b.biological_count(seed('movement_schedules'), leadsheets)] + cycle_forms(procedures, leadsheets, seed('movement_schedules'), seed('procedure_requirements'), seed('requirements')) + forms_families_c.FORMS + forms_letters.FORMS
    catalogue.sort(key=lambda f: f['number'])
    controls_register(catalogue, seed('cycles'))
    for f in catalogue:
        f['version'] = f.get('version', 1)
        f['ar_status'] = 'draft_pending_review'
    problems = check(catalogue, procedures, standards)
    if problems:
        raise SystemExit('catalogue problems:\n  ' + '\n  '.join(problems))
    graph, gproblems = build_graph(catalogue)
    if gproblems:
        raise SystemExit('graph problems:\n  ' + '\n  '.join(gproblems))
    os.makedirs(FORMS_DIR, exist_ok=True)
    frozen = freeze_earlier_versions(catalogue)
    for f in catalogue:
        with open(os.path.join(FORMS_DIR, f['id'] + '.json'), 'w', encoding='utf-8') as fh:
            json.dump(f, fh, ensure_ascii=False, indent=1)
    product = [at_version(f, 1) for f in catalogue if f['number'] <= PRODUCT_FORMS]
    ext = [at_version(f, 1) for f in catalogue if PRODUCT_FORMS < f['number'] <= EXT_FORMS]
    more = [at_version(f, 1) for f in catalogue if f['number'] > EXT_FORMS]
    v2 = [at_version(f, 2) for f in catalogue if f['version'] >= 2]
    v3 = [at_version(f, 3) for f in catalogue if f['version'] >= 3]
    write_module(OUT, product, '(form id, form definition as JSON), in catalogue order.')
    write_module(OUT_EXT, ext, '(form id, form definition as JSON), forms 15 onwards, in catalogue order.')
    write_module(OUT_MORE, more, '(form id, form definition as JSON), forms 39 onwards at version 1, in catalogue order.')
    write_module(OUT_V2, v2, '(form id, form definition as JSON): version 2 of every form revised since its first module, in catalogue order.')
    write_module(OUT_V3, v3, '(form id, form definition as JSON): version 3 of every form revised twice, in catalogue order.')
    with open(os.path.join(FORMS_DIR, 'GRAPH.json'), 'w', encoding='utf-8') as fh:
        json.dump(graph, fh, ensure_ascii=False, indent=1)
    with open(OUT_GRAPH, 'w', encoding='utf-8') as fh:
        fh.write('// GENERATED by tools/gen_forms.py from the form catalogue. Do not edit.\n'
                 '// Attribution: Thebes Core Team. Licence: Apache 2.0.\n\n'
                 'module {\n  /// The dependency graph between forms, as canonical JSON: nodes and edges\n'
                 '  /// (from, from_field, to, to_field, via, kind), derived from the definitions.\n'
                 f'  public let GRAPH : Text = {mo(json.dumps(graph, ensure_ascii=False, separators=(",", ":")))};\n\n'
                 '  /// The definitions instantiated per leadsheet, by id: read without parsing a definition.\n'
                 f'  public let PER : [Text] = [{", ".join(mo(f["id"]) for f in catalogue if f.get("per") == "leadsheet")}];\n\n'
                 '  /// The form that owns each computation kind (the paper a firm form reads through `paper.<kind>`):\n'
                 '  /// a lookup, so that no definition is parsed to find an owner.\n'
                 f'  public let OWNERS : [(Text, Text)] = [{", ".join(f"({mo(kind)}, {mo(fid)})" for fid, kinds in OWNS.items() for kind in kinds)}];\n\n'
                 '  /// The edges into each form, as canonical JSON per target: a read of one form parses\n'
                 '  /// its own edges and no other.\n'
                 '  public let INTO : [(Text, Text)] = [\n'
                 + ''.join(f'    ({mo(f["id"])}, {mo(json.dumps([e for e in graph["edges"] if e["to"] == f["id"]], ensure_ascii=False, separators=(",", ":")))}),\n' for f in catalogue)
                 + '  ];\n'
                 '};\n')
    nfields = sum(len(s_['fields']) for f in catalogue for s_ in f['sections'])
    served = {pid for f in catalogue for pid in f['procedures']}
    print(f'wrote {len(catalogue)} forms ({nfields} fields, {sum(1 for f in catalogue if f["kind"] == "letter")} letters) to forms/, '
          f'{len(product)} to {os.path.relpath(OUT)} (unchanged), {len(ext)} to {os.path.relpath(OUT_EXT)} (unchanged), {len(more)} to {os.path.relpath(OUT_MORE)} {len(v2)} at version 2 to {os.path.relpath(OUT_V2)} and {len(v3)} at version 3 to {os.path.relpath(OUT_V3)} ({frozen} newly frozen); '
          f'{len(served)} of {len(procedures)} procedures served by a form, {len(graph["edges"])} graph edges')


def self_test():
    """The generator refuses what it must: a duplicate id, an unknown procedure, an unknown
    type, a missing Arabic label, an unknown autofill root, a cycle in the graph, and a
    catalogue that leaves a procedure unserved."""
    import copy
    procedures = seed('procedures')
    leadsheets = seed('leadsheets')
    standards = seed('standards')
    base = FORMS + forms_families_a.FORMS + forms_families_b.FORMS + cycle_forms(procedures, leadsheets)
    for f in base:
        f['version'] = 1
        f['ar_status'] = 'draft_pending_review'
    assert check(base, procedures, standards) == [], 'the catalogue itself must pass'
    assert build_graph(base)[1] == [], 'the graph itself must pass'

    def variant(mutate):
        forms = copy.deepcopy(base)
        mutate(forms)
        return forms

    def expect(name, forms, needle, graph=False):
        probs = build_graph(forms)[1] if graph else check(forms, procedures, standards)
        assert any(needle in p for p in probs), f'{name}: expected a problem containing {needle!r}, got {probs[:3]}'

    def dup(forms): forms[1]['id'] = forms[0]['id']
    def proc(forms): forms[0]['procedures'].append('P-FSL-999')
    def ty(forms): forms[0]['sections'][1]['fields'][0]['type'] = 'datetime'
    def ar(forms): forms[0]['sections'][1]['fields'][0]['label']['ar'] = ''
    def root(forms): forms[0]['sections'][0]['fields'][0]['autofill'] = 'ledger.cash'
    def unserved(forms): forms[-1]['procedures'] = []
    def cycle(forms):
        # F06 reads F07 while F07 reads F06's paper: a cycle
        forms[5]['sections'][1]['fields'][0]['autofill'] = 'form.F07-SAMPLING-PLAN.population'
    expect('duplicate id', variant(dup), 'duplicate form id')
    expect('unknown procedure', variant(proc), 'unknown procedure')
    expect('unknown type', variant(ty), 'unknown type')
    expect('missing Arabic', variant(ar), 'missing ar label')
    expect('unknown root', variant(root), 'autofill root unknown')
    expect('unserved', variant(unserved), 'served by no form')
    expect('cycle', variant(cycle), 'cycle', graph=True)
    print('self-test: 7 refusals as expected')


if __name__ == '__main__':
    if '--self-test' in sys.argv:
        self_test()
    else:
        main()
