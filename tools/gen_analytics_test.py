def instances_block():
    out = []
    for k, ls in enumerate(POPULATED):
        inp, expected, line, values = PAPERS[ls]
        fid = f'{BASE}@{ls}'
        out.append(f'instances += 1;')
        out.append(f'ignore must("fill {fid}", F.save(s, ff, staff, false, 20, 1, {mo(fid)}, j({jl({"values": values})})));')
        out.append(f'ignore must("compute {fid}", compute({mo(fid)}, {jl(inp)}));')
        out.append(f'figures += 4;')
        out.append(f'check("{ls}: the expectation is the oracle\'s", field(view(staff, {mo(fid)}), ["live", "expected"]) == #str({mo(line["expected"])}));')
        out.append(f'check("{ls}: the threshold is the oracle\'s", field(view(staff, {mo(fid)}), ["live", "threshold"]) == #str({mo(expected["threshold"])}));')
        out.append(f'check("{ls}: the difference is the oracle\'s", field(view(staff, {mo(fid)}), ["live", "difference"]) == #str({mo(line["difference"])}));')
        out.append(f'check("{ls}: whether to investigate is the oracle\'s", field(view(staff, {mo(fid)}), ["live", "investigate"]) == #bool({"true" if line["investigate"] else "false"}));')
        if ls not in (FAR, UNSIGNED):
            out.append(f'ignore must("prepare {fid}", F.sign(s, ff, staff, 21, 1, {mo(fid)}, "prepare", "2026-02-01T{9 + k // 12:02d}:{(k * 5) % 60:02d}"));')
    return '\n'.join(out)


def main():
    other = next(ls for ls in POPULATED if ls not in (FAR, UNSIGNED))
    far_values = dict(PAPERS[FAR][3], investigation='Management attributes the movement to the new export line; shipping documents and price lists corroborate it.')
    body = HEAD
    subs = {
        '__FIXTURE__': mo(FIXTURE), '__SCALED__': mo(SCALED), '__MAT_INPUT__': jl(MAT_INPUT), '__BASE__': BASE, '__N__': str(len(POPULATED)),
        '__REV_NET__': mo(str(NET['LS-REV'])), '__PM__': mo(PM), '__INSTANCES__': instances_block(),
        '__FAR__': FAR, '__UNSIGNED__': UNSIGNED, '__OTHER__': other,
        '__FAR_INVESTIGATED__': jl({'values': far_values}), '__FAR_DIFF__': mo(PAPERS[FAR][2]['difference']), '__OTHER_DIFF__': mo(PAPERS[other][2]['difference']),
    }
    for k, v in subs.items():
        assert k in body, k
        body = body.replace(k, v)
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(body)
    print(f'wrote {os.path.relpath(OUT)}: {len(POPULATED)} instances, the far one {FAR} (difference {PAPERS[FAR][2]["difference"]} against a threshold of {PAPERS[FAR][1]["threshold"]}), {UNSIGNED} left for the gate')


if __name__ == '__main__':
    main()
