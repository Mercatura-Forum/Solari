def paper_for(ls):
    """An expectation from the prior period: the growth the ledger shows, so the difference is
    the rounding of the rate; for one leadsheet a flat expectation, far from the balance."""
    recorded, prior = NET[ls], PRIOR.get(ls, Decimal(0))
    if ls == FAR:
        model = {'kind': 'prior_growth', 'prior': str(prior), 'growth_pct': '0'}
        values = {'model': 'prior_growth', 'growth_pct': '0'}
    elif prior != 0:
        growth = ((recorded / prior - 1) * 100).quantize(Decimal('0.01'))
        model = {'kind': 'prior_growth', 'prior': str(prior), 'growth_pct': str(growth)}
        values = {'model': 'prior_growth', 'growth_pct': str(growth)}
    else:
        model = {'kind': 'proof_in_total', 'components': [str(recorded)]}
        values = {'model': 'proof_in_total', 'components': [{'name': 'Balance per the ledger', 'amount': str(recorded)}]}
    inp = {'lines': [{'name': ls, 'recorded': str(recorded), 'model': model}], 'performance_materiality': PM, 'threshold_pct': '50'}
    expected = c.analytical_review(inp['lines'], PM, '50', '0')
    line = expected['lines'][0]
    values.update({k: v for k, v in required_values(FORM).items() if k not in values})
    values['threshold_pct'] = '50'
    return inp, expected, line, values


