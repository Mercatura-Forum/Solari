"""Generate motoko/test/Letters.test.mo: the letter templates and the act of sending them.

Every template (forms/F41 to F49) is checked here before anything is generated: each of its
paragraphs, in both languages, refers only to fields the template carries or to attributes of
the engagement, so the letter renders from the file with nothing missing. Then, on an
engagement, every letter is filled with its required values, prepared and sent: the
communication record and the request record are checked against what was sent (with whom,
the subject, the procedure the letter serves, the addressee, the dates), the request counts
on the paper live, a draft is refused, a second send of the same version is refused, a
procedure the letter does not serve is refused, and a letter changed after sending is a new
version that can be sent again.

Attribution: Thebes Core Team. Licence: Apache 2.0.
"""
import json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..')
OUT = os.path.join(ROOT, 'motoko', 'test', 'Letters.test.mo')
sys.path.insert(0, HERE)
from gen_graph_test import load_forms, required_values, mo  # noqa: E402
from forms_letters import SENT  # noqa: E402

FORMS = load_forms()
LETTERS = [FORMS[f] for f in sorted(FORMS) if f in SENT]
assert len(LETTERS) == 9, [f['id'] for f in LETTERS]
ENGAGEMENT_ATTRS = {'client', 'period_start', 'period_end', 'currency', 'framework', 'audit_standard'}
PLACEHOLDER = re.compile(r'\{\{(engagement\.([a-z_]+)|field:([a-z_]+)|table:([a-z_]+))\}\}')


def jl(obj):
    return mo(json.dumps(obj, ensure_ascii=False, separators=(',', ':')))


def check_template(f):
    """Every placeholder of every paragraph in both languages resolves; both languages have the
    same number of paragraphs; every table placeholder names a table field."""
    fields = {fd['id']: fd for s_ in f['sections'] for fd in s_['fields']}
    assert f['kind'] == 'letter' and 'letter' in f, f['id']
    assert len(f['letter']['en']) == len(f['letter']['ar']), f['id']
    n = 0
    for lang in ('en', 'ar'):
        for para in f['letter'][lang]:
            for m in PLACEHOLDER.finditer(para):
                n += 1
                if m.group(2):
                    assert m.group(2) in ENGAGEMENT_ATTRS, (f['id'], m.group(0))
                elif m.group(3):
                    assert m.group(3) in fields, (f['id'], m.group(0))
                else:
                    assert m.group(4) in fields and fields[m.group(4)]['type'] == 'table', (f['id'], m.group(0))
    assert n > 0
    return n


PLACEHOLDERS = {f['id']: check_template(f) for f in LETTERS}

