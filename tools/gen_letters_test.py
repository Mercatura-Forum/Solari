def fill_for(f):
    v = required_values(f)
    for k in ('request_date',):
        if k in v:
            v[k] = '2026-02-01'
    if 'reply_by' in v:
        v['reply_by'] = '2026-03-01'
    if 'consent_date' in v:
        v['consent_date'] = '2026-01-20'
    if 'prior_period_end' in v:
        v['prior_period_end'] = '2024-12-31'
    return v


def letters_block():
    out = []
    n = 0
    per_proc = {}
    for k, f in enumerate(LETTERS):
        fid = f['id']
        with_, proc = SENT[fid]
        per_proc[proc] = per_proc.get(proc, 0) + 1              # two templates may serve one procedure: the count is shared
        stamp = f'2026-02-01T{10 + k:02d}:00'
        addressee = 'Delta Textiles' if 'CONFIRMATION' in fid else ('Nile Legal Partners' if 'LEGAL' in fid else ('Previous & Co' if 'PREDECESSOR' in fid else 'The audit committee'))
        if fid != 'F41-CONFIRMATION-RECEIVABLE':
            out.append(f'ignore must("fill {fid}", F.save(s, ff, staff, false, {10 + k}, 1, {mo(fid)}, j({jl({"values": fill_for(f)})})));')
            out.append(f'ignore must("prepare {fid}", F.sign(s, ff, staff, {10 + k}, 1, {mo(fid)}, "prepare", "2026-02-01T{9 + k:02d}:30"));')
        out.append(f'let sent_{k} = must("send {fid}", send({mo(fid)}, {mo(with_)}, {mo(proc)}, {mo(addressee)}, {mo(stamp)}));')
        out.append('sentLetters += 1;')
        out.append(f'check("{fid}: the communication names the party, the subject and the time", field(sent_{k}, ["communication", "fields", "with"]) == #str({mo(with_)}) and field(sent_{k}, ["communication", "fields", "direction"]) == #str("sent") and field(sent_{k}, ["communication", "fields", "form"]) == #str("written") and field(sent_{k}, ["communication", "fields", "at"]) == #str({mo(stamp)}) and Text.contains(Py.textOr(field(sent_{k}, ["communication", "fields"]), "subject", ""), #text {mo(fid)}));')
        out.append(f'check("{fid}: the request names the procedure, the addressee and the due date", field(sent_{k}, ["request", "fields", "procedure"]) == #str({mo(proc)}) and field(sent_{k}, ["request", "fields", "addressee"]) == #str({mo(addressee)}) and field(sent_{k}, ["request", "fields", "state"]) == #str("open") and field(sent_{k}, ["request", "fields", "due"]) == #str("2026-03-15"));')
        out.append(f'check("{fid}: the paper counts the requests of its procedure live", field(view(staff, {mo(fid)}), ["live", "sent"]) == #num("{per_proc[proc]}"));')
        n += 1
    return '\n'.join(out), n


def main():
    block, n = letters_block()
    f41 = FORMS['F41-CONFIRMATION-RECEIVABLE']
    fill = fill_for(f41)
    fill2 = dict(fill, balance='250000.00')
    body = HEAD
    subs = {
        '__F41_PARAS__': str(len(f41['letter']['en'])), '__F41_FILL__': jl({'values': fill}), '__F41_FILL2__': jl({'values': fill2}),
        '__LETTERS__': block, '__N_SENT__': str(n + 1), '__N_PLACEHOLDERS__': str(sum(PLACEHOLDERS.values())),
    }
    for k, v in subs.items():
        assert k in body, k
        body = body.replace(k, v)
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(body)
    print(f'wrote {os.path.relpath(OUT)}: {len(LETTERS)} templates, {sum(PLACEHOLDERS.values())} placeholders resolved in both languages, {n + 1} letters sent')


if __name__ == '__main__':
    main()
